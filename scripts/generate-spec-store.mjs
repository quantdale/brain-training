#!/usr/bin/env node
/**
 * generate-spec-store.mjs — deterministic consolidation of OpenSpec delta
 * specs into the main spec store (`openspec/specs/`). (Explore finding F-1.)
 *
 * WHY: the repository declares `schema: spec-driven`, where
 * `openspec/specs/<capability>/spec.md` is the current normative requirement
 * store that delta specs apply against — but the store was empty. Every
 * capability's requirements lived only as delta specs inside change folders
 * (132 capabilities / 140 spec files), so "what does capability X currently
 * require?" could only be answered by replaying ~70 change folders, and the
 * MODIFIED/REMOVED deltas had literally nothing to modify.
 *
 * MODEL: each capability is currently authored by exactly one change folder.
 * The generator replays each capability's delta sections in document order:
 *   `## ADDED Requirements`    -> requirement is emitted
 *   `## MODIFIED Requirements` -> requirement is emitted after the ADDED ones
 *                                 (later text supersedes earlier text)
 *   `## REMOVED Requirements`  -> an already-emitted requirement with the same
 *                                 title is dropped
 * If one capability ever gains a second delta source, the generator FAILS
 * LOUDLY instead of guessing a replay order.
 *
 * The main specs are GENERATED: do not hand-edit `openspec/specs/**`. Change
 * folders stay the authored source; run this script to project them. CI runs
 * `--check` (declared in GOVERNANCE.greenMain.enforcedGateSet) so drift between
 * the change deltas and the main store is a detectable red gate.
 *
 * Usage:
 *   node scripts/generate-spec-store.mjs           regenerate openspec/specs/
 *   node scripts/generate-spec-store.mjs --check   exit 1 on drift (CI gate)
 *
 * Exit codes: 0 = ok, 1 = drift or consolidation error, 2 = usage error.
 */
import fs from 'node:fs';
import path from 'node:path';
import { fileURLToPath } from 'node:url';

const root = path.resolve(path.dirname(fileURLToPath(import.meta.url)), '..');
const CHANGES_DIR = path.join(root, 'openspec', 'changes');
const SPECS_DIR = path.join(root, 'openspec', 'specs');
const GENERATED_MARKER = 'Generated by scripts/generate-spec-store.mjs';

/** Recursively collect `specs/<capability>/spec.md` under openspec/changes. */
function findDeltaSpecs() {
  const found = [];
  function walk(dir) {
    for (const entry of fs.readdirSync(dir, { withFileTypes: true })) {
      const full = path.join(dir, entry.name);
      if (entry.isDirectory()) {
        if (entry.name === 'specs') {
          collectCapabilities(full, full);
        } else {
          walk(full);
        }
      }
    }
  }
  function collectCapabilities(specsRoot, dir) {
    for (const entry of fs.readdirSync(dir, { withFileTypes: true })) {
      const full = path.join(dir, entry.name);
      if (entry.isDirectory()) collectCapabilities(specsRoot, full);
      else if (entry.isFile() && entry.name === 'spec.md') {
        const capability = path.relative(specsRoot, dir).split(path.sep).join('/');
        found.push({ capability, file: full });
      }
    }
  }
  walk(CHANGES_DIR);
  return found.sort((a, b) => a.capability.localeCompare(b.capability));
}

/**
 * Split a delta spec into ordered {kind, title, body} requirement blocks.
 * `kind` is ADDED | MODIFIED | REMOVED. Blocks keep document order.
 */
function parseDelta(text) {
  const lines = text.split(/\r?\n/);
  const blocks = [];
  let kind = null;
  let current = null;
  const close = () => {
    if (current) {
      // Collapse runs of blank lines (source deltas vary) and trim the block
      // edges so rendered specs stay markdownlint-clean (MD012) and stable.
      const body = current.bodyLines.join('\n').replace(/\n{3,}/g, '\n\n').replace(/^\n+|\n+$/g, '');
      // Ensure one blank line after every heading (MD022/MD032): some source
      // deltas put scenario lists directly under the heading.
      const lines = body.split('\n');
      const normalized = [];
      for (let i = 0; i < lines.length; i += 1) {
        normalized.push(lines[i]);
        if (/^#{2,6} /.test(lines[i]) && lines[i + 1] !== undefined && lines[i + 1] !== '') {
          normalized.push('');
        }
      }
      current.body = normalized.join('\n');
      blocks.push(current);
      current = null;
    }
  };
  for (const line of lines) {
    const section = line.match(/^## (ADDED|MODIFIED|REMOVED) Requirements\s*$/);
    if (section) {
      close();
      kind = section[1];
      continue;
    }
    const req = line.match(/^### Requirement:\s*(.+?)\s*$/);
    if (req && kind) {
      close();
      current = { kind, title: req[1], bodyLines: [] };
      continue;
    }
    if (/^## /.test(line)) {
      close();
      kind = null;
      continue;
    }
    if (current) current.bodyLines.push(line);
  }
  close();
  return blocks;
}

/** Apply ADDED/MODIFIED/REMOVED replay for one capability. */
function replay(blocks, label) {
  const ordered = [];
  const byTitle = new Map();
  for (const block of blocks) {
    if (block.kind === 'REMOVED') {
      const idx = ordered.findIndex((b) => b.title === block.title);
      if (idx < 0) {
        throw new Error(
          `${label}: REMOVED requirement "${block.title}" does not match any replayed requirement — fix the delta or the generator model`,
        );
      }
      ordered.splice(idx, 1);
      byTitle.delete(block.title);
      continue;
    }
    // ADDED and MODIFIED both emit; MODIFIED sections appear later in the
    // document, so their text (the superseding contract) wins on name clashes.
    const existing = byTitle.get(block.title);
    if (existing) {
      existing.body = block.body;
      continue;
    }
    const entry = { title: block.title, body: block.body };
    byTitle.set(block.title, entry);
    ordered.push(entry);
  }
  return ordered;
}

function renderSpec(capability, changeId, sourceRel, requirements) {
  const reqText = requirements
    .map((r) => `### Requirement: ${r.title}\n\n${r.body}`)
    .join('\n\n');
  return (
    `# ${capability} Specification\n\n`
    + `## Purpose\n\n`
    + `Consolidated current requirements for \`${capability}\`. Generated from the\n`
    + `normative delta specification of \`${changeId}\`; behavioral rationale and\n`
    + `design context live in that change's proposal/design documents.\n\n`
    + `## Requirements\n\n`
    + `${reqText}\n\n`
    + `<!-- ${GENERATED_MARKER} from ${sourceRel}. Do not edit by hand: run\n`
    + `     \`node scripts/generate-spec-store.mjs\` to regenerate. -->\n`
  );
}

function buildStore() {
  const deltas = findDeltaSpecs();
  const byCapability = new Map();
  for (const { capability, file } of deltas) {
    const rel = path.relative(root, file).split(path.sep).join('/');
    const changeId = rel.split('/specs/')[0].replace(/^openspec\/changes\/(?:archive\/)?/, '');
    const sources = byCapability.get(capability) ?? [];
    sources.push({ file, rel, changeId });
    byCapability.set(capability, sources);
  }
  const outputs = new Map();
  for (const capability of [...byCapability.keys()].sort()) {
    const sources = byCapability.get(capability);
    if (sources.length !== 1) {
      // Multiple delta sources for one capability would need a chronological
      // replay order the generator cannot derive safely today — fail loudly.
      throw new Error(
        `capability '${capability}' has ${sources.length} delta sources (${sources.map((s) => s.rel).join(', ')}) — extend the generator with an explicit replay order before regenerating`,
      );
    }
    const { file, rel, changeId } = sources[0];
    const requirements = replay(parseDelta(fs.readFileSync(file, 'utf8')), rel);
    if (requirements.length === 0) {
      throw new Error(`capability '${capability}' replays to zero requirements (${rel})`);
    }
    outputs.set(capability, renderSpec(capability, changeId, rel, requirements));
  }
  return outputs;
}

function listExistingSpecs() {
  const found = [];
  if (!fs.existsSync(SPECS_DIR)) return found;
  function walk(dir) {
    for (const entry of fs.readdirSync(dir, { withFileTypes: true })) {
      const full = path.join(dir, entry.name);
      if (entry.isDirectory()) walk(full);
      else if (entry.isFile() && entry.name === 'spec.md') {
        found.push(path.relative(SPECS_DIR, full).split(path.sep).join('/'));
      }
    }
  }
  walk(SPECS_DIR);
  return found.sort();
}

function main() {
  const args = process.argv.slice(2);
  const check = args.includes('--check');
  if (args.some((a) => a.startsWith('-') && a !== '--check')) {
    console.error('Usage: node scripts/generate-spec-store.mjs [--check]');
    process.exit(2);
  }
  let outputs;
  try {
    outputs = buildStore();
  } catch (error) {
    console.error(`generate-spec-store: FAIL — ${error.message}`);
    process.exit(1);
  }

  const expectedPaths = [...outputs.keys()].map((c) => `${c}/spec.md`).sort();
  const existingPaths = listExistingSpecs();

  if (check) {
    const problems = [];
    for (const rel of expectedPaths) {
      const full = path.join(SPECS_DIR, rel);
      if (!fs.existsSync(full)) problems.push(`missing: openspec/specs/${rel}`);
      else if (fs.readFileSync(full, 'utf8') !== outputs.get(rel.split('/spec.md')[0])) {
        problems.push(`drift: openspec/specs/${rel} differs from regenerated content`);
      }
    }
    for (const rel of existingPaths) {
      if (!expectedPaths.includes(rel)) problems.push(`stale: openspec/specs/${rel} has no delta source`);
    }
    if (problems.length) {
      console.error('generate-spec-store: FAIL — spec store drift:');
      for (const p of problems) console.error(`- ${p}`);
      console.error('Run `node scripts/generate-spec-store.mjs` and commit the result.');
      process.exit(1);
    }
    console.log(`generate-spec-store: OK (${expectedPaths.length} specs match their delta sources)`);
    return;
  }

  for (const [capability, content] of outputs) {
    const full = path.join(SPECS_DIR, capability, 'spec.md');
    fs.mkdirSync(path.dirname(full), { recursive: true });
    fs.writeFileSync(full, content, 'utf8');
  }
  for (const rel of existingPaths) {
    if (!expectedPaths.includes(rel)) fs.rmSync(path.join(SPECS_DIR, rel));
  }
  console.log(`generate-spec-store: wrote ${expectedPaths.length} specs under openspec/specs/`);
}

main();
